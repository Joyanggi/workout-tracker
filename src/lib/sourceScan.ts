/**
 * 소스 스캔 유틸 — 인바리언트 테스트 공용.
 *
 * **주석을 걷어내고 검사한다.** 금지하려는 표현을 주석에 예시로 적는 일이 잦고
 * (그게 좋은 주석이다), 그때마다 스캔이 자기 설명을 위반으로 신고한다.
 * X3에서 한 번, X8에서 또 겪었다 — 두 번 겪은 것은 유틸로 만든다.
 *
 * 허용 목록으로 넘기지 않는 이유: 그러면 그 파일 안의 **진짜 위반**을 못 잡는다.
 */

/** `//` 줄 주석과 `/* *\/` 블록 주석을 지운다. 문자열 안의 `//`(URL)도 지워지지만 무해하다 */
export function stripComments(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '')
}
