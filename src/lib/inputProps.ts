/**
 * iOS 자동완성(QuickType 연락처 제안) 억제 (G5).
 *
 * iOS는 이름 없는 텍스트 필드를 연락처 필드로 오인해 키보드 위에 이름·주소 제안을 띄운다.
 * 세트 무게를 입력하는데 연락처가 뜨는 것이 실사용 피드백이었다.
 *
 * **한 객체로 모아 전 필드에 spread한다.** 필드마다 손으로 네 속성을 적으면
 * 새 입력을 추가할 때 반드시 하나를 빠뜨린다 — 이 프로젝트에서 같은 부류를
 * 여러 번 겪었다 (워밍업 제외, 대체 해석, 어시스티드 방향).
 *
 * ⚠ **한계**: iOS는 `autocomplete="off"`를 완전히 존중하지 않는다. `name` 미지정이
 * 통상 제안을 줄이지만 **보장은 실기기 확인으로만 가능**하다.
 * 남는 필드가 있으면 그 필드의 속성 조합을 기록할 것 (짐작으로 반복 수정 금지).
 *
 * (이 주석은 v1.2에 `inputMode`도 이 조합에 든다고 적었는데 **사실이 아니다** — 이 객체는
 * `inputMode`를 설정하지 않는다. 숫자 키패드는 `NumberStepper`가 따로 지정한다.
 * W1 조사에서 발견해 바로잡았다.)
 *
 * `name`은 **일부러 넣지 않는다** — 넣는 순간 iOS가 그 이름으로 필드 종류를 추측한다.
 */
export const NO_AUTOFILL = {
  autoComplete: 'off',
  autoCorrect: 'off',
  autoCapitalize: 'off',
  spellCheck: false,
} as const

/**
 * W1 1차 실험 — iOS가 `autocomplete="off"`를 무시하는 경우의 우회 토큰.
 *
 * **비표준 값**이라 iOS가 아는 어떤 필드 종류에도 매칭되지 않는다. `"off"`는 iOS가
 * "힌트 없음"으로 읽고 자체 추론으로 넘어가지만, 알 수 없는 토큰은 그 추론까지 막는
 * 경향이 있다 (표준 우회로 통용되는 방식).
 *
 * **머신 세팅 메모 한 곳에만 붙인다.** 변수를 하나만 바꿔야 실기기 결과가 무엇을
 * 말하는지 알 수 있다 — 열 곳에 동시에 넣으면 효과가 있어도 무엇이 들었는지 모른다.
 * `NO_AUTOFILL` 객체는 건드리지 않는다 (계획서 지시).
 */
