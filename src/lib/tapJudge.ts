/**
 * 탭 판정 (CC12) — **뗄 때 발화한다.**
 *
 * 피드백: "− + 에 손을 올리고만 있어도 쭉 올라간다. 드래그해도 바뀐다. 손 뗐을 때만
 * 반응해야 할 것 같다. 오터치 복구가 귀찮다."
 *
 * 이전 동작은 의도된 설계였다 — `NumberStepper`가 롱프레스 가속 반복(400ms 후 110ms
 * 간격, 8회 후 55ms)을 구현하고 있었고(DESIGN §5.2), 가정은 "큰 점프를 빠르게"였다.
 * **실사용 환경이 그 가정을 이겼다**: 땀·장갑·기구 사이 이동 중의 오터치에서 가속은
 * 큰 점프 장치가 아니라 **오터치 증폭 장치**다. 복구 비용이 이득보다 크다.
 *
 * 큰 점프는 가운데 직접 입력이 이미 담당한다 — 반복을 없애도 경로가 남는다.
 *
 * 순수 함수로 두는 이유: 슬롭·경계 판정은 화면 없이 검증할 수 있어야 하고,
 * 이 판정이 틀리면 "눌렀는데 안 되는" 또는 "안 눌렀는데 되는" 둘 다 가능해진다.
 */

/**
 * 이동 허용 반경 (px).
 *
 * 스크롤 제스처와 탭을 가르는 표준적인 크기다. 이보다 작게 잡으면 손가락이 미세하게
 * 움직이는 정상 탭이 무발화가 되고(가장 나쁜 실패), 크게 잡으면 스크롤 중 스친 것이
 * 값을 바꾼다.
 */
export const TAP_SLOP_PX = 12

export interface TapPoint {
  x: number
  y: number
}

/**
 * 이 pointerup을 탭으로 볼 것인가.
 *
 * `down`이 없으면 (이 버튼에서 시작하지 않은 릴리즈) 무발화 — 다른 곳에서 눌러
 * 끌고 온 손가락이 값을 바꾸면 안 된다.
 */
export function isTap(down: TapPoint | null, up: TapPoint): boolean {
  if (!down) return false
  return Math.hypot(up.x - down.x, up.y - down.y) <= TAP_SLOP_PX
}
